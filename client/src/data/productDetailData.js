const SHADE_NATURAL_BLACK = 'natural-black-beard-colour';
const SHADE_BLACK_BROWN = 'black-brown-beard-colour';
const SHADE_DARK_BROWN = 'dark-brown-beard-colour';

const genericFallback = shadeInfo[SHADE_NATURAL_BLACK];

export function getProductDetailData(slug) {
  if (!slug) return genericFallback;
  const s = String(slug).toLowerCase();
  if (shadeInfo[s]) return shadeInfo[s];
  if (s.includes('natural') && s.includes('black')) return shadeInfo[SHADE_NATURAL_BLACK];
  if (s.includes('beard') && s.includes('colour') && s.includes('black') && !s.includes('brown')) return shadeInfo[SHADE_NATURAL_BLACK];
  if (s === 'natural-black') return shadeInfo[SHADE_NATURAL_BLACK];
  if (s.includes('dark') && s.includes('brown')) return shadeInfo[SHADE_DARK_BROWN];
  if (s === 'dark-brown') return shadeInfo[SHADE_DARK_BROWN];
  if (s.includes('black') && s.includes('brown')) return shadeInfo[SHADE_BLACK_BROWN];
  if (s === 'black-brown') return shadeInfo[SHADE_BLACK_BROWN];
  if (s.includes('black')) return shadeInfo[SHADE_NATURAL_BLACK];
  if (s.includes('brown')) return shadeInfo[SHADE_DARK_BROWN];
  return genericFallback;
}

export const SHADE_DISPLAY_ORDER = [SHADE_NATURAL_BLACK, SHADE_BLACK_BROWN, SHADE_DARK_BROWN];

export function getShadeSortRank(slug) {
  const s = String(slug || '').toLowerCase();
  if (s.includes('natural') || s === 'natural-black' || s.includes(SHADE_NATURAL_BLACK) || (s.includes('black') && !s.includes('brown'))) return 0;
  if (s.includes('black-brown') || s.includes('black') && s.includes('brown') && !s.includes('dark')) return 1;
  if (s.includes('dark-brown') || s.includes('dark') && s.includes('brown')) return 2;
  return 99;
}

